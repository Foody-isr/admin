import {test,expect} from "@playwright/test";
import type {DraftStatePayload} from "../../src/lib/website-v3/types";

// Real renderers; writes stay in the synthetic local API.
test("Pink Coffee survives slide edits, reload and publication",async ({page,context,request},testInfo)=>{
  test.setTimeout(300_000);
  await page.addInitScript(()=>{
    localStorage.setItem("foody_restaurant_token","isolated-ui-fixture");
    localStorage.setItem("foody_restaurant_user",JSON.stringify({id:1,full_name:"Demo",role:"manager",email:"demo@foody.test"}));
    localStorage.setItem("foody_restaurant_ids","[1]");localStorage.setItem("foody-admin-locale","fr");
  });
  await context.route("**/*",route=>["localhost","127.0.0.1"].includes(new URL(route.request().url()).hostname)?route.continue():route.abort());
  const draft=async ():Promise<DraftStatePayload>=>(await(await request.get("http://127.0.0.1:18081/api/v1/restaurants/1/website-draft")).json()).state;
  const seed=await draft();seed.pages=seed.pages.slice(0,2);seed.pages[1].slug="commander";
  seed.sections=[{id:8100,section_type:"hero_banner",page:"home",page_id:1,sort_order:0,is_visible:true,layout:"centered",content:{headline:"Notre café",image_url:"http://localhost:3000/assets/placeholder-item-lg.svg",cta_text:"Commander",cta_link:"/order"},settings:{}}];
  expect((await request.put("http://127.0.0.1:18081/api/v1/restaurants/1/website-draft",{data:seed})).ok()).toBe(true);
  expect((await request.post("http://127.0.0.1:18081/api/v1/restaurants/1/website-publish")).ok()).toBe(true);
  await page.goto("/1/website-v3");
  await page.getByRole("button",{name:"Design du site",exact:true}).click();
  await page.getByRole("button",{name:"Thèmes du site",exact:true}).click();
  await page.locator("article.sqe-theme-card").filter({hasText:"Pink Coffee"}).getByRole("button",{name:"Aperçu",exact:true}).click();
  await page.getByRole("button",{name:"Appliquer le thème",exact:true}).click();
  await expect.poll(async()=>(await draft()).sections.find(s=>s.id===8100)?.layout).toBe("campaign");
  const preview=page.frameLocator('iframe[title="Aperçu de Accueil"]');
  await expect(preview.locator(".website-campaign")).toBeVisible({timeout:120_000});
  await page.getByRole("button",{name:"Terminé",exact:true}).click();
  await page.getByRole("button",{name:"Bannière principale",exact:true}).click();
  await page.getByRole("button",{name:"Cliquez ici pour modifier",exact:true}).click();
  const panel=page.locator(".sqe-inspector");
  const slideDetails=panel.locator("fieldset").first().locator(":scope > details");
  await slideDetails.first().locator(":scope > summary").click();
  await panel.locator('[data-field-id="section.content.slides.0.headline"]').fill("Just more coffee");
  await panel.locator('[data-field-id="section.content.slides.0.cta_text"]').fill("Choisir ma boisson");
  await panel.locator('[data-field-id="section.settings.slide_duration_seconds"]').fill("12");
  await panel.locator('[data-field-id="section.settings.image_fit"]').selectOption("contain");
  await panel.locator('[data-field-id="section.settings.controls_alignment"]').selectOption("left");
  const desktopWidth=panel.locator('[data-field-id="section.settings.card_width_percent"]');
  await desktopWidth.fill("");
  await desktopWidth.pressSequentially("88");
  await expect(desktopWidth).toHaveValue("88");
  await panel.locator('[data-field-id="section.settings.card_width_percent_mobile"]').fill("82");
  await panel.locator('[data-field-id="section.settings.card_gap"]').fill("18");
  await panel.locator('input[data-field-id="section.settings.show_counter"]').setChecked(true);
  await expect(preview.locator('[data-campaign-counter]')).toBeVisible();
  await panel.locator('input[data-field-id="section.settings.show_counter"]').setChecked(false);
  await panel.locator('input[data-field-id="section.settings.show_playback_control"]').setChecked(false);
  await panel.locator('input[data-field-id="section.settings.autoplay"]').setChecked(true);
  await expect(panel.getByText("Le bouton Pause reste disponible lorsque la lecture automatique est activée.",{exact:true})).toBeVisible();
  await expect(preview.locator('.website-campaign-play')).toBeVisible();
  await panel.locator('input[data-field-id="section.settings.autoplay"]').setChecked(false);
  await panel.getByRole("button",{name:"Ajouter une diapositive",exact:true}).click();
  const slides=async()=>(await draft()).sections.find(s=>s.id===8100)?.content.slides as Array<{headline:string}>;
  await expect.poll(async()=>(await slides()).length).toBe(4);
  await slideDetails.last().locator(":scope > summary").click();
  await panel.getByRole("button",{name:"Supprimer la diapositive 4",exact:true}).click();
  await panel.getByRole("button",{name:"Descendre 1",exact:true}).click();
  await expect.poll(async()=>(await slides())[1].headline).toBe("Just more coffee");
  await panel.getByRole("button",{name:"Monter 2",exact:true}).click();
  await expect.poll(async()=>(await slides())[0].headline).toBe("Just more coffee");
  await page.reload();
  await expect(preview.getByRole("heading",{name:"Just more coffee",exact:true}).first()).toBeVisible({timeout:120_000});
  await expect(preview.locator('[data-campaign-counter]')).toHaveCount(0);
  await expect(preview.locator('.website-campaign-play')).toHaveCount(0);
  await preview.locator('.website-featured[data-presentation="campaign"]').click({position:{x:2,y:2}});
  const featuredPanel=page.locator('.sqe-featured-editor');
  await expect(featuredPanel).toBeVisible();
  await featuredPanel.locator('select').first().selectOption("custom");
  await featuredPanel.getByRole('button',{name:"Choisir des articles",exact:true}).click();
  const picker=page.getByRole('dialog');
  await picker.locator('[data-field-id="section.featured.select_all"]').click();
  await picker.getByRole('button',{name:"Enregistrer",exact:true}).click();
  await expect.poll(async()=>((await draft()).sections.find(section=>section.section_type==="menu_highlights")?.content.item_ids as number[]).length).toBe(12);
  await featuredPanel.locator('[data-field-id="section.settings.content_max_width"]').fill("1100");
  await featuredPanel.locator('[data-field-id="section.settings.row_spacing"]').fill("44");
  await featuredPanel.locator('fieldset[data-field-id="section.settings.item_image_backgrounds"] select').selectOption("12");
  const productColor=featuredPanel.locator('input[type="text"][data-field-id="section.settings.item_image_backgrounds.12"]');
  await productColor.fill("");
  await productColor.pressSequentially("#112233",{delay:150});
  await expect(productColor).toHaveValue("#112233");
  await expect.poll(async()=>((await draft()).sections.find(section=>section.section_type==="menu_highlights")?.settings.item_image_backgrounds as Record<string,string>)?.["12"]).toBe("#112233");
  await page.reload();
  await expect(preview.locator('.website-featured-card')).toHaveCount(12);
  await expect(preview.locator('.website-featured-card[data-item-id="12"] .website-featured-image')).toHaveCSS('background-color','rgb(17, 34, 51)');
  await page.getByRole('button',{name:"En-tête",exact:true}).click();
  await page.locator('[data-header-panel="navigation"] .sqh-accordion-heading > button').click();
  await page.locator('[data-field-id="site.header.navigation.hamburger_style"]').selectOption("standard");
  const menuIconSize=page.locator('[data-field-id="site.header.navigation.hamburger_size"]');
  await menuIconSize.fill("");
  await menuIconSize.pressSequentially("32");
  await expect(menuIconSize).toHaveValue("32");
  await page.locator('[data-field-id="site.header.navigation.hamburger_stroke"]').fill("3");
  await page.locator('[data-header-panel="icons"] .sqh-accordion-heading > button').click();
  await page.locator('input[data-field-id="site.header.icons.cart"]').setChecked(true);
  await expect.poll(async()=>((await draft()).config.nav_layout as {header:{icons:{cart:boolean}}}).header.icons.cart).toBe(true);
  await page.locator('input[data-field-id="site.header.icons.cart"]').setChecked(false);
  await page.getByRole("button",{name:"Format de l’aperçu",exact:true}).click();
  await page.getByRole("menuitemradio",{name:"Vue téléphone",exact:true}).click();
  await expect(preview.getByRole("heading",{name:"Just more coffee",exact:true}).first()).toHaveCSS("font-size","44px");
  await page.getByRole("button",{name:"Format de l’aperçu",exact:true}).click();
  await page.getByRole("menuitemradio",{name:"Vue ordinateur",exact:true}).click();
  await expect(page.getByRole("button",{name:"Publier",exact:true})).not.toHaveAttribute("title",/Vérifiez/);
  const published=page.waitForResponse(response=>response.url().endsWith("/website-publish")&&response.request().method()==="POST");
  await page.getByRole("button",{name:"Publier",exact:true}).click();expect((await published).ok()).toBe(true);
  const saved=await draft();expect(saved.pages).toHaveLength(2);expect(saved.pages[1].settings).toEqual(seed.pages[1].settings);
  expect(saved.sections.find(s=>s.section_type==="menu_highlights")?.settings).toMatchObject({card_presentation:"campaign",columns:4,mobile_columns:2});
  expect(saved.sections.find(s=>s.id===8100)?.settings).toMatchObject({controls_alignment:"left",show_counter:false,show_playback_control:false,autoplay:false,card_width_percent:88,card_width_percent_mobile:82,card_gap:18});
  expect(saved.sections.find(s=>s.section_type==="menu_highlights")?.settings).toMatchObject({content_max_width:1100,row_spacing:44,item_image_backgrounds:{"12":"#112233"},show_descriptions:true,show_prices:false,show_buttons:false});
  const storefront=await context.newPage();await storefront.goto("http://localhost:3000/r/atelier-foody?lang=fr");
  for(const width of [1440,375]){
    await storefront.setViewportSize({width,height:1000});
    await expect(storefront.getByRole("heading",{name:"Just more coffee",exact:true}).first()).toBeVisible();
    await expect(storefront.locator('.website-featured[data-presentation="campaign"]')).toBeVisible();
    await expect(storefront.locator('.website-featured-card')).toHaveCount(12);
    await expect(storefront.locator('.website-featured-description')).toHaveCount(12);
    await expect(storefront.locator('.website-featured-price, .website-featured-button')).toHaveCount(0);
    await expect(storefront.locator('.website-featured-card[data-item-id="12"] .website-featured-image')).toHaveCSS('background-color','rgb(17, 34, 51)');
    await expect(storefront.locator('[data-campaign-counter], .website-campaign-play')).toHaveCount(0);
    await expect(storefront.locator('[data-field-site-header-navigation-hamburger-style="standard"]').first()).toBeAttached();
    expect(await storefront.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
    await storefront.screenshot({path:testInfo.outputPath(`pink-coffee-${width}.png`),fullPage:true});
  }
  await storefront.locator('.website-featured-card[data-item-id="1"]').click();
  await expect(storefront.getByRole('dialog')).toContainText('Double Espresso');
});
